// Regenerates src/data/grammarIndex.js: the light list of grammar topics the
// Grammar page shows (id, title, icon, tag and a short description), so that
// page does not have to load ~3.5 MB of guides and exercises just to draw cards.
//
//   node scripts/gen-grammar-index.mjs
//
// Run it after adding or renaming a grammar topic. src/data/grammarIndex.test.js
// fails when the index is stale.
import fs from 'node:fs';
import { grammarData } from '../src/data/grammarData.js';
import { grammarSnippet } from '../src/data/grammarSnippet.js';

const index = {};
for (const [level, data] of Object.entries(grammarData)) {
  index[level] = {
    label: data.label,
    topics: (data.topics || []).map((t) => ({
      id: t.id,
      title: t.title,
      icon: t.icon,
      ...(t.tag ? { tag: t.tag } : {}),
      snippet: grammarSnippet(t),
    })),
  };
}

const body = `// GENERATED by scripts/gen-grammar-index.mjs - do not edit by hand.\n`
  + `export const grammarIndex = ${JSON.stringify(index, null, 2)};\n`;
fs.writeFileSync(new URL('../src/data/grammarIndex.js', import.meta.url), body);
console.log('grammarIndex.js written:', Object.values(index).map((l) => l.topics.length).join(' / '), 'topics per level');
